"""Replace a graph's seeds by the released TOGT-Planner's single cold start.

The released TrajData::initData uses each waypoint center and assigns each
segment its Euclidean distance divided by speedGuess. Its internal PVAJ states
are then generated by MINCO, rather than set independently. This exporter maps
that curve into our finite solver's coordinates without solving another method.
"""
import argparse
import json
from pathlib import Path
import shutil

import casadi as ca
import numpy as np

from convex_timevarying_window.comparisons.论文实验.实验2.higher_swing import scenario


def export(source: Path, output: Path, *, speed_guess: float = 1.) -> None:
    if speed_guess <= 0.:
        raise ValueError('speedGuess must be positive')
    shutil.copytree(source, output)
    path = output / 'manifest.json'
    manifest = json.loads(path.read_text())
    track, _ = scenario.build_case(scenario.Case(level=manifest['level']))
    nodes = np.vstack([track.start, *[window.center0 for window in track.windows], track.goal])
    durations = np.linalg.norm(np.diff(nodes, axis=0), axis=1) / speed_guess
    if len(durations) != manifest['n'] or np.any(durations <= 0.):
        raise ValueError('TOGT initial durations do not match the graph')
    original_seed = manifest['initials'][0]
    nvar = manifest['nvar']
    z = np.zeros(nvar)
    z[manifest['n']:manifest['velocity_start']] = np.asarray(original_seed['finite'])[
        manifest['n']:manifest['velocity_start']]
    parameters = np.asarray(original_seed['parameters'], dtype=float)
    parameters[0] = durations.sum()
    parameters[1:1+manifest['n']] = np.cumsum(durations)
    extended = np.r_[z, np.zeros(len(manifest['slack_scale']))]
    trajectory = ca.Function.load(str(output / 'trajectory.casadi'))
    physical, generated_times, coefficients, points, *_ = trajectory(extended, parameters)
    np.testing.assert_allclose(np.asarray(generated_times).ravel(), durations, rtol=0., atol=1e-10)
    np.testing.assert_allclose(np.asarray(points).T, nodes[1:-1], rtol=0., atol=1e-8)
    residual = np.asarray(ca.Function.load(str(output / 'global_uniform_dynamics.casadi'))(
        coefficients, generated_times)).ravel()
    manifest['initials'] = [dict(index=0, original=np.asarray(physical).ravel().tolist(),
                                 parameters=parameters.tolist(), finite=extended.tolist())]
    manifest['initialization'] = dict(
        source='released TOGT-Planner TrajData::initData',
        speed_guess_mps=speed_guess,
        waypoint_rule='static window centers',
        segment_time_rule='Euclidean distance / speedGuess',
        internal_pvaj_rule='MINCO from center waypoints and segment times',
        number_of_starts=1)
    path.write_text(json.dumps(manifest, indent=2) + '\n')
    (output / 'initial_diagnostic.json').write_text(json.dumps(dict(
        durations_s=durations.tolist(), total_time_s=float(durations.sum()),
        sampled_dynamic_positive_rows=int((residual > 0.).sum()),
        sampled_dynamic_max_residual=float(residual.max()),
        source='released TOGT-Planner',
    ), indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--speed-guess', type=float, default=1.)
    args = parser.parse_args()
    export(args.source, args.output, speed_guess=args.speed_guess)
